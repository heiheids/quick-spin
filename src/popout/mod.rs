//! 弹出子窗口（popout）。
//!
//! ## 这是什么
//!
//! 从侧边栏某个选项卡上右键 → 「弹出子窗口」，把**那一个选项卡**单独拆成
//! 一个独立窗口：没有侧边栏，只有图标网格 + 自己的标题栏（4 个按钮）。
//!
//! ## 模块边界（刻意拆开，一个文件只干一件事）
//!
//! | 文件 | 职责 |
//! |---|---|
//! | `state.rs` | 持久化模型：开关 / 位置 / 尺寸 / 吸附 / 钉住 / 名字 / 独立配色 |
//! | `dock.rs` | 吸附跟随的几何（纯算术，创建与跟随共用同一个函数） |
//! | `layout.rs` | 这个窗口自己的布局（**不复用**主窗口的 `ui::layout`） |
//! | `painter.rs` | 绘制：标题栏（4 个按钮）+ 图标网格 |
//! | `icons.rs` | 内容快照 + 这个窗口自己的图标管线（加载线程与位图缓存） |
//! | `launch.rs` | 点一格 = 启动它（复用 `shell::launch`，不另写启动路径） |
//! | `window.rs` | 窗口行为：吸附跟随 / 脱离拖动 / 钉住 / 就地改名 |
//! | `report.rs` | 回报通道：弹窗自己关了时要让装配层知道（否则菜单文案是错的） |
//!
//! 为什么布局不复用主窗口那份：主窗口的 `Layout` 里耦合了侧栏、滚动、搜索、
//! 设置面板这些弹出窗口根本没有的东西。硬塞进去会让那份布局变成"两个窗口
//! 的并集"，改任何一边都要回头看另一边 —— 正是"一页海量代码"的来源。
//!
//! ## 与主窗口的关系
//!
//! 它是**独立的顶层窗口**（有自己的 HWND 与交换链），不是主窗口的子控件：
//! 需求要求它既能吸附跟随，也能被拖走、钉到桌面。`WS_CHILD` 做不到这些。
//! 两者共享同一个 UI 线程与同一个 D3D11 设备（见 `render::device`），
//! 只是各有各的交换链。
//!
//! ## 允许多个
//!
//! 一个选项卡最多一个弹出窗口，不同选项卡可以同时各开一个，所以状态是
//! **映射**而不是单个字段。键用选项卡的 `key`（配置里的稳定标识），
//! 不用下标 —— 下标在增删选项卡后会漂移。

